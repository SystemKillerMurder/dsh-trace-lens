import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
const root = path.dirname(fileURLToPath(import.meta.url))
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const packageName = JSON.parse(read('package.json')).name
const stripExports = source => source.replace(/^export \{[^}]*\};?\s*$/gm, '').replace(/^export /gm, '')
const fzstdPath = path.join(path.dirname(createRequire(import.meta.url).resolve('fzstd')), '../esm/index.mjs')
const fzstd = `const fzstd = (() => {\n${stripExports(fs.readFileSync(fzstdPath, 'utf8'))}\nreturn { decompress }\n})()`
const model = stripExports(read('data-model.js'))
const importer = stripExports(read('session-import.js'))
const ui = read('view.js')
const importUi = read('import-view.js')
const steadyTabs = read('steady-tabs.js')
const registration = `
    return {
      inject: ['slots', 'sessions', 'uiSession', 'uiConversation'],
      apply(ctx) {
        const sources = new WeakMap()
        const sourceFor = binding => {
          let source = sources.get(binding)
          if (source === undefined) {
            const target = ctx.uiConversation.binding(binding).target('trajectory')
            source = { getSnapshot: () => target.getSnapshot() ?? { eventNodes: [], requests: [], runningCalls: [] }, subscribe: listener => target.subscribe(listener) }
            sources.set(binding, source)
          }
          return source
        }
        ctx.uiSession.provide({
          hooks: ['trace'],
          resolve: binding => ({ hooks: { trace: sourceFor(binding) } }),
        })
        ctx.slots.inject('conversation.view', () => ctx.slots.register({
          name: 'conversation.view', id: 'trace-lens', order: 20, label: 'Trace', scope: 'session',
          inject: sessionId => ({
            loadOlder: async () => {
              const session = ctx.sessions.binding(sessionId)?.session
              if (session === undefined) return false
              const trajectory = ctx.uiConversation.binding(sessionId).target('trajectory')
              const before = trajectory.getSnapshot()
              await session.loadOlder()
              return trajectory.getSnapshot() !== before
            },
          }),
        }, TraceLensView))
        ctx.slots.inject('settings.section', () => ctx.slots.register({
          name: 'settings.section', id: 'trace-lens-import', order: 90, label: () => 'Session 分析',
        }, SessionImportSection))
        ctx.effect(() => () => { closeAnalyzer() }, 'trace-lens import overlay')
        ctx.effect(() => installSteadyTabs(), 'trace-lens steady view tabs')
      },
    }
  }
})
`
fs.writeFileSync(path.join(root, 'client.js'), `// Generated by build.mjs; edit data-model.js, session-import.js, view.js, and import-view.js instead.
window.__ModuleLoader__.load({id:${JSON.stringify(packageName)},factory(require){
const React = require('react'); const h = React.createElement;
${fzstd}
${model}
${importer}
${ui}
${importUi}
${steadyTabs}
${registration}`)
console.log('Built Trace Lens client bundle')
